#!/usr/bin/env python3
"""Render a harness results.json into docs/benchmarks.md.

Writes only what was measured. A cell with no data says "not measured" rather
than being left blank or guessed at, and the provenance block always names the
machine and commit the numbers came from.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

TARGET_ORDER = ["Cobra", "clap", "picocli", "Laret JVM", "Laret native"]
# The Targets table labels a target by language; results.json names it by target.
TARGET_NAMES = {
    "Cobra (Go)": "Cobra",
    "clap (Rust)": "clap",
    "picocli (Java)": "picocli",
    "Laret JVM": "Laret JVM",
    "Laret native": "Laret native",
}
NOT_MEASURED = "not measured"

BUILDS = [
    ("Cobra (Go)", '`go build -trimpath -ldflags="-s -w"`'),
    ("clap (Rust)", "`cargo build --release`"),
    ("picocli (Java)", "`java -jar`"),
    ("Laret JVM", "`java -jar` (shadow jar)"),
    ("Laret native", "GraalVM Native Image"),
]


def ms(value: float | None) -> str:
    return f"{value:.1f} ms" if value is not None else NOT_MEASURED


def us(value: float | None) -> str:
    return f"{value:.2f} µs" if value is not None else NOT_MEASURED


def mib(value: int | None) -> str:
    return f"{value / 1024:.1f} MiB" if value is not None else NOT_MEASURED


def verdict(measurement: dict, check: str) -> str:
    if check not in measurement.get("checks", {}):
        return NOT_MEASURED
    return "pass" if measurement["checks"][check] else "**fail**"


def index(measurements: list[dict]) -> dict:
    return {(m["target"], m["scenario"], json.dumps(m["parameters"], sort_keys=True)): m for m in measurements}


def find(measurements: list[dict], target: str, scenario: str, **params) -> dict | None:
    for m in measurements:
        if m["target"] != target or m["scenario"] != scenario:
            continue
        if all(m["parameters"].get(key) == value for key, value in params.items()):
            return m
    return None


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(out)


def targets_present(measurements: list[dict]) -> list[str]:
    seen = {m["target"] for m in measurements}
    ordered = [t for t in TARGET_ORDER if t in seen]
    return ordered + sorted(seen - set(ordered))


def render(document: dict) -> str:
    measurements = document["measurements"]
    targets = targets_present(measurements)
    provenance = document.get("provenance", {})

    out: list[str] = []
    add = out.append

    add("# Concurrency and Parallel Execution Benchmarks")
    add("")
    add(
        "Laret measured against four other CLI stacks on the orchestration work a\n"
        "framework does *after* start-up: fan-out scheduling, event coalescing, streaming\n"
        "pipelines and cancellation under load. Cold-start numbers are a different\n"
        "question and are not on this page."
    )
    add("")
    add(
        "This file is generated by `benchmarks/harness/render.py`. It is not generated\n"
        "into `site/docs`, because `laret doc generate` overwrites that tree."
    )
    add("")

    unbuilt = document.get("skipped_targets") or []
    if unbuilt:
        add(f"> Requested but not built, so not measured: {', '.join(unbuilt)}.")
        add("")

    add("## Provenance")
    add("")
    add("Numbers are only meaningful next to the machine that produced them.")
    add("")
    add(table(
        ["Field", "Value"],
        [
            ["Laret commit", provenance.get("laret_commit") or NOT_MEASURED],
            ["Date", provenance.get("date") or NOT_MEASURED],
            ["Host", provenance.get("host") or NOT_MEASURED],
            ["Kernel", provenance.get("kernel") or NOT_MEASURED],
            ["CPU", (provenance.get("cpu") or NOT_MEASURED).strip()],
            ["Pinned cores", provenance.get("pinned_cpus") or NOT_MEASURED],
            ["Go toolchain", provenance.get("go") or NOT_MEASURED],
            ["Rust toolchain", provenance.get("rust") or NOT_MEASURED],
            ["JDK", provenance.get("jdk") or NOT_MEASURED],
            ["GraalVM", provenance.get("graalvm") or NOT_MEASURED],
        ],
    ))
    add("")

    add("## Targets")
    add("")
    measured = set(targets)
    not_requested = set(document.get("not_requested_targets") or [])
    unbuilt_set = set(unbuilt)

    def status(label: str) -> str:
        name = TARGET_NAMES.get(label, label)
        if name in measured:
            return "measured"
        if name in not_requested:
            return "not run in this configuration"
        if name in unbuilt_set:
            return "not built"
        return NOT_MEASURED

    add(table(
        ["Target", "Build", "This run"],
        [[label, build, status(label)] for label, build in BUILDS],
    ))
    add("")
    add(
        "All five implement the same four commands with the same flags and the same\n"
        "stdout contract, so the harness invokes them identically."
    )
    add("")
    if not_requested:
        add(
            f"> This run measured only {', '.join(sorted(measured))}. "
            f"{', '.join(sorted(not_requested))} were not requested, so the tables\n"
            "> below have no row for them. The pull-request gate restricts the suite to\n"
            "> the Laret targets at reduced scale; the full five-target comparison runs\n"
            "> nightly."
        )
        add("")
    if document.get("quick"):
        add(
            "> Reduced scale (`--quick`): these are correctness parameters, not the\n"
            "> scales the contract names. Do not read the timings as a comparison."
        )
        add("")

    add("## Rules")
    add("")
    add("- **No external I/O.** Payloads are CPU or memory bound.")
    add("- **Pinned and isolated.** Every process is pinned with `taskset`; each scenario")
    add("  finishes and releases its memory before the next begins.")
    add("- **Warmed up.** A discarded dry run precedes the timed runs.")
    add("- **Linux only.** Pinning and peak RSS (`/proc/<pid>/status` `VmHWM`) are")
    add("  Linux-specific, and numbers are not comparable across operating systems.")
    add("- **Native abstractions.** Where a framework has its own parallel dispatch or")
    add("  pipeline, that is what is measured.")
    add("")

    add("## Scenario A - Parallel fan-out and fan-in")
    add("")
    add(
        "Dispatch N independent sub-tasks concurrently, join them, aggregate the results.\n"
        "Each task yields briefly and returns a token. This measures the tax the framework\n"
        "adds on top of the language's own concurrency model."
    )
    add("")
    task_counts = sorted({m["parameters"].get("tasks") for m in measurements if m["scenario"] == "A-fanout"} - {None})
    for tasks in task_counts:
        add(f"### N = {tasks:,}")
        add("")
        rows = []
        for target in targets:
            m = find(measurements, target, "A-fanout", tasks=tasks)
            rows.append([
                target,
                ms(m["wall_clock_ms"]) if m else NOT_MEASURED,
                us(m["overhead_us_per_unit"]) if m else NOT_MEASURED,
                mib(m["peak_rss_kb"]) if m else NOT_MEASURED,
                verdict(m, "sum") if m else NOT_MEASURED,
            ])
        add(table(["Target", "Wall clock", "Overhead per task", "Peak RSS", "Aggregate"], rows))
        add("")

    add("## Scenario B - Event storm")
    add("")
    add(
        "The CLI enters watch mode and a storm of events is fired into it. The framework\n"
        "must filter, debounce and coalesce them into exactly one execution of the target\n"
        "command. Coalescing is strict pass/fail."
    )
    add("")
    rows = []
    for target in targets:
        m = find(measurements, target, "B-storm")
        rows.append([
            target,
            ms(m["wall_clock_ms"]) if m else NOT_MEASURED,
            mib(m["peak_rss_kb"]) if m else NOT_MEASURED,
            verdict(m, "coalesced_to_one_run") if m else NOT_MEASURED,
        ])
    add(table(["Target", "Wall clock", "Peak RSS", "Coalescing"], rows))
    add("")

    add("## Scenario C - Concurrent streaming pipeline")
    add("")
    add(
        "A three-stage pipeline with every stage live at once: stage one emits lines,\n"
        "stage two filters and transforms concurrently, stage three aggregates a count.\n"
        "This measures I/O multiplexing and whether the pipeline stays synchronised\n"
        "without deadlocking, dropping lines or exhausting memory."
    )
    add("")
    rows = []
    for target in targets:
        m = find(measurements, target, "C-pipeline")
        rows.append([
            target,
            ms(m["wall_clock_ms"]) if m else NOT_MEASURED,
            us(m["overhead_us_per_unit"]) if m else NOT_MEASURED,
            mib(m["peak_rss_kb"]) if m else NOT_MEASURED,
            verdict(m, "lines_correct") if m else NOT_MEASURED,
        ])
    add(table(["Target", "Wall clock", "Overhead per line", "Peak RSS", "Lines correct"], rows))
    add("")

    add("## Scenario D - Cancellation storm")
    add("")
    add(
        "A long-running command spawns background workers; a termination signal arrives\n"
        "200 ms after start-up. The framework must propagate cancellation, run every\n"
        "cleanup hook in reverse registration order, and exit with `128 + signal`."
    )
    add("")
    for scenario, signal_name in (("D-cancel-SIGTERM", "SIGTERM"), ("D-cancel-SIGINT", "SIGINT")):
        add(f"### {signal_name}")
        add("")
        rows = []
        for target in targets:
            m = find(measurements, target, scenario)
            rows.append([
                target,
                ms(m["cancellation_latency_ms"]) if m else NOT_MEASURED,
                str(m["exit_code"]) if m and m["exit_code"] is not None else NOT_MEASURED,
                verdict(m, "reverse_registration_order") if m else NOT_MEASURED,
                mib(m["peak_rss_kb"]) if m else NOT_MEASURED,
            ])
        add(table(["Target", "Cancellation latency", "Exit code", "Cleanup order", "Peak RSS"], rows))
        add("")

    add("## Reproducing")
    add("")
    add("```bash")
    add("# Linux only.")
    add("benchmarks/harness/build.sh")
    add("python3 benchmarks/harness/harness.py --out results.json")
    add("python3 benchmarks/harness/render.py results.json > docs/benchmarks.md")
    add("```")
    add("")
    add(
        "CI does not gate on any timing. Pull requests run the scenarios once at reduced\n"
        "scale and assert only the deterministic properties. The full five-target suite\n"
        "runs nightly and uploads `results.json` and this table as artifacts."
    )
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("results", help="results.json produced by harness.py")
    args = parser.parse_args()

    document = json.loads(Path(args.results).read_text())
    if document.get("schema_version") != 1:
        sys.exit(f"Unsupported schema_version: {document.get('schema_version')!r}")
    sys.stdout.write(render(document))
    return 0


if __name__ == "__main__":
    sys.exit(main())
